export function formatIDR(n) {
  return new Intl.NumberFormat("id-ID", { style: "currency", currency: "IDR", maximumFractionDigits: 0 }).format(n);
}

export function getPriceBuckets(items) {
  const prices = items.map((i) => Number(i.price) || 0);
  const min = Math.min(...prices);
  const max = Math.max(...prices);
  const range = max - min;
  const t1 = Math.round(min + range / 3);
  const t2 = Math.round(min + (range * 2) / 3);
  return [
    { key: "all", label: "Semua Harga", test: () => true },
    { key: "low", label: `Di bawah ${formatIDR(t1)}`, test: (p) => p <= t1 },
    { key: "mid", label: `${formatIDR(t1)} - ${formatIDR(t2)}`, test: (p) => p > t1 && p <= t2 },
    { key: "high", label: `Di atas ${formatIDR(t2)}`, test: (p) => p > t2 },
  ];
}
