// Ubah nama paket jadi id yang aman dipakai sebagai key/identifier (mis. "Konsultasi Singkat" -> "konsultasi-singkat").
export function slugify(text) {
  return String(text)
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "") || "paket";
}

